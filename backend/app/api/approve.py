"""Approval execution endpoint for ShopEasy support bot.

Enforces Security Rule #8 & #9:
- Single-use, expiring approval tokens
- Owner check: authenticated user must match token.user_id
- Executes risky operations (cancel order) only upon explicit human approval
"""

from typing import Any, Dict
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from app.agent.tools import execute_order_cancellation
from app.core.approval import consume_approval_token
from app.core.auth import get_current_user
from app.db import get_db
from app.models.message import Message
from app.models.user import User

router = APIRouter(prefix="/approve", tags=["approve"])


class ApproveRequest(BaseModel):
    token: str = Field(..., description="Approval token generated by the agent")
    session_id: str = Field(None, description="Optional chat session ID to record completion")


class ApproveResponse(BaseModel):
    success: bool
    action: str
    message: str
    details: Dict[str, Any]


@router.post("", response_model=ApproveResponse, status_code=status.HTTP_200_OK)
def approve_action(
    payload: ApproveRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> ApproveResponse:
    """Validate and execute an approved action."""
    # 1. Validate & consume approval token (checks expiry, single-use, and user_id ownership)
    approval_data = consume_approval_token(payload.token, current_user.id)
    action = approval_data["action"]
    details = approval_data["details"]

    # 2. Execute the approved action
    if action == "cancel_order":
        order_id = details["order_id"]
        result = execute_order_cancellation(order_id, current_user.id, db=db)

        if not result.get("success"):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=result.get("error", "Failed to cancel order."),
            )

        # 3. Optionally record the confirmation in the messages table
        if payload.session_id:
            confirm_msg = Message(
                session_id=payload.session_id,
                role="assistant",
                content=result["message"],
                sources=None,
            )
            db.add(confirm_msg)
            db.commit()

        return ApproveResponse(
            success=True,
            action=action,
            message=result["message"],
            details=result,
        )

    else:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Unknown action '{action}'.",
        )
